export const getProvinceById = (provinceIdOrName: string): NepalProvince => {
  const normalized = provinceIdOrName.toLowerCase();
  const match = NEPAL_PROVINCES.find(
    (p) =>
      p.id.toLowerCase() === normalized ||
      p.nameEn.toLowerCase().includes(normalized) ||
      p.nameNp.includes(provinceIdOrName)
  );
  return match || NEPAL_PROVINCES[0]; // fallback Bagmati
};

export const getCityById = (province: NepalProvince, cityIdOrName: string): NepalCity => {
  const normalized = cityIdOrName.toLowerCase();
  const match = province.cities.find(
    (c) =>
      c.id.toLowerCase() === normalized ||
      c.nameEn.toLowerCase().includes(normalized) ||
      c.nameNp.includes(cityIdOrName) ||
      c.districtEn.toLowerCase().includes(normalized)
  );
  return match || province.cities[0];
};
